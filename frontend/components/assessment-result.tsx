import { resolveFindings, type DamageFinding, type PartFinding } from "@/lib/assessment";
import { formatPercent, readable } from "@/lib/format";
import type { AssessmentResponse, ReportResult, VerificationResult } from "@/lib/types";
import { ImageIcon, ShieldIcon } from "./icons";

export function AssessmentResult({
  result,
  originalPreview,
}: {
  result: AssessmentResponse;
  originalPreview: string | null;
}) {
  const findings = resolveFindings(result);
  const { image, damage_detections, part_detections } = result.cv_output;

  return (
    <section className="results-shell" aria-live="polite">
      <div className="section-heading results-heading">
        <div>
          <span className="kicker">Assessment {result.analysis_id.slice(0, 8)}</span>
          <h2>Preliminary result</h2>
        </div>
        <span className={`verification-pill status-${result.verification.status}`}>
          <ShieldIcon />
          {readable(result.verification.status)}
        </span>
      </div>

      {!image.usable && (
        <div className="result-notice notice-warning" role="status">
          <strong>Image not assessed</strong>
          <p>{image.quality_note ?? "The image did not pass the input quality check, so no detection was run."}</p>
        </div>
      )}

      <div className="results-layout">
        <DetectionImage overlay={result.overlay_data_url} originalPreview={originalPreview} imageId={image.id} />

        <div className="detections-panel">
          <div className="card-label">
            <span>Computer-vision detections</span>
            <small>From the CV models</small>
          </div>

          <div className="detection-summary">
            <div><strong>{damage_detections.length}</strong><span>Damage detections</span></div>
            <div><strong>{part_detections.length}</strong><span>Vehicle parts</span></div>
            <div><strong>{findings.linkedCount}</strong><span>Part associations</span></div>
          </div>

          <div className="panel-section">
            <h3>Damage findings</h3>
            {findings.damages.length === 0 ? (
              <p className="empty-state">
                No damage detections were returned by the computer-vision pipeline for this image.
                This is not a determination that the vehicle is free of damage.
              </p>
            ) : (
              <ul className="damage-list">
                {findings.damages.map((finding) => (
                  <DamageFindingCard key={finding.damage.id} finding={finding} />
                ))}
              </ul>
            )}
          </div>

          <div className="panel-section">
            <h3>Vehicle parts detected</h3>
            {findings.parts.length === 0 ? (
              <p className="empty-state">
                No vehicle-part detections were returned by the computer-vision pipeline for this image.
              </p>
            ) : (
              <ul className="part-list">
                {findings.parts.map((finding) => (
                  <PartChip key={finding.part.id} finding={finding} />
                ))}
              </ul>
            )}
          </div>

          <p className="panel-scope">
            Scope: damage class, detection confidence and vehicle-part location only.
          </p>
        </div>
      </div>

      <VerificationSummary verification={result.verification} />

      <div className="report-grid">
        <ReportSummary report={result.report} />
        <aside className="recommendation-card">
          <span>Review guidance</span>
          <p>{result.recommendation}</p>
          <hr />
          <small>{result.disclaimer}</small>
        </aside>
      </div>
    </section>
  );
}

function DetectionImage({
  overlay,
  originalPreview,
  imageId,
}: {
  overlay: string | null;
  originalPreview: string | null;
  imageId: string;
}) {
  return (
    <figure className="overlay-card">
      <div className="card-label">
        <span>Detection overlay</span>
        <small>{imageId}</small>
      </div>
      <div className="overlay-frame">
        {overlay ? (
          // The overlay is a data URL generated by the local API; boxes are drawn by the backend.
          // eslint-disable-next-line @next/next/no-img-element
          <img src={overlay} alt="Vehicle image with computer-vision detection boxes drawn by the backend" />
        ) : originalPreview ? (
          <>
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={originalPreview} alt="Uploaded vehicle image without detection boxes" />
            <p className="overlay-missing">Detection overlay unavailable — showing the uploaded image without detection boxes.</p>
          </>
        ) : (
          <div className="overlay-placeholder">
            <ImageIcon />
            <p>Detection overlay unavailable for this result.</p>
          </div>
        )}
      </div>
      {overlay && (
        <figcaption className="overlay-legend">
          <span><i className="legend-damage" />Damage detection</span>
          <span><i className="legend-part" />Vehicle-part detection</span>
          <small>Boxes and labels drawn by the backend</small>
        </figcaption>
      )}
    </figure>
  );
}

const NO_PART_DETAIL: Record<Exclude<DamageFinding["state"], "linked">, string> = {
  unmatched: "The matching step found no overlapping vehicle part for this detection.",
  no_record: "No association record was returned for this detection.",
  unresolved_part: "The association referenced a part that is not among the returned part detections.",
};

function DamageFindingCard({ finding }: { finding: DamageFinding }) {
  const { damage, state, part, score, alternatives, issues, flaggedAmbiguous } = finding;
  const tied = alternatives.some((alternative) => alternative.tiedWithLeader);

  return (
    <li className="damage-card-item">
      <div className="damage-head">
        <div>
          <span className="damage-id">{damage.id}</span>
          <h4>{readable(damage.class)}</h4>
        </div>
        <ConfidenceBadge value={damage.confidence} label="detection confidence" />
      </div>

      <div className={`association association-${state === "linked" ? "linked" : "none"}`}>
        {state === "linked" && part ? (
          <>
            <span className="association-label">Matched part</span>
            <strong>{readable(part.class)}</strong>
            <span className="association-meta">
              Part {part.id} · {formatPercent(part.confidence)} part confidence
              {score !== null && (
                <>
                  {" · "}
                  <abbr title="Share of the damage box covered by the part box. Not a calibrated probability.">
                    {formatPercent(score)} overlap score
                  </abbr>
                </>
              )}
            </span>
          </>
        ) : (
          <>
            <strong>No confident part association</strong>
            <span className="association-meta">
              {state === "linked" ? "" : NO_PART_DETAIL[state]}
            </span>
          </>
        )}
      </div>

      {(flaggedAmbiguous || tied) && (
        <div className="badge-row">
          {flaggedAmbiguous && <span className="status-badge badge-warning">Ambiguous · flagged by verification</span>}
          {tied && <span className="status-badge badge-neutral">Tied overlap score</span>}
        </div>
      )}

      {alternatives.length > 0 && (
        <div className="alternatives">
          <span className="association-label">Other overlapping parts</span>
          <ul>
            {alternatives.map((alternative) => (
              <li key={alternative.partId}>
                <span>{alternative.part ? readable(alternative.part.class) : `Unknown part (${alternative.partId})`}</span>
                <b>{formatPercent(alternative.score)}</b>
              </li>
            ))}
          </ul>
        </div>
      )}

      {issues.length > 0 && (
        <ul className="finding-issues">
          {issues.map((issue, index) => (
            <li key={`${issue.code}-${issue.path}-${index}`} className={`issue-${issue.level}`}>
              {issue.message}
            </li>
          ))}
        </ul>
      )}
    </li>
  );
}

function PartChip({ finding }: { finding: PartFinding }) {
  const { part, linkedDamageIds, issues } = finding;
  return (
    <li className={`part-chip ${linkedDamageIds.length > 0 ? "is-linked" : ""}`}>
      <span className="part-name">{readable(part.class)}</span>
      <span className="part-meta">
        {part.id} · {formatPercent(part.confidence)}
        {linkedDamageIds.length > 0 && ` · linked to ${linkedDamageIds.join(", ")}`}
      </span>
      {issues.length > 0 && <span className="part-flag" title={issues.map((issue) => issue.message).join(" ")}>Flagged</span>}
    </li>
  );
}

function ConfidenceBadge({ value, label }: { value: number; label: string }) {
  return (
    <span className="confidence-badge" aria-label={`${formatPercent(value)} ${label}`}>
      <b>{formatPercent(value)}</b>
      <small>{label}</small>
    </span>
  );
}

const VERIFICATION_COPY: Record<VerificationResult["status"], { title: string; detail: string; tone: string }> = {
  verified: {
    title: "Verification passed",
    detail: "The structured record passed verification and is eligible for report generation.",
    tone: "success",
  },
  manual_review: {
    title: "Manual review required",
    detail: "The verification layer flagged items for assessor attention. The record was not sent to the language model.",
    tone: "warning",
  },
  rejected: {
    title: "Verification rejected",
    detail: "The structured record failed verification and was not sent to the language model.",
    tone: "danger",
  },
};

function VerificationSummary({ verification }: { verification: VerificationResult }) {
  const copy = VERIFICATION_COPY[verification.status];
  if (verification.status === "verified" && verification.issues.length === 0) {
    return (
      <div className={`verification-card tone-${copy.tone}`}>
        <div className="verification-head"><span className="verification-symbol">✓</span><div><strong>{copy.title}</strong><p>{copy.detail}</p></div></div>
      </div>
    );
  }
  return (
    <div className={`verification-card tone-${copy.tone}`} role="status">
      <div className="verification-head">
        <span className="verification-symbol">!</span>
        <div><strong>{copy.title}</strong><p>{copy.detail}</p></div>
      </div>
      {verification.issues.length > 0 && (
        <ul>
          {verification.issues.map((issue, index) => (
            <li key={`${issue.code}-${issue.path}-${index}`}>
              <span className={`issue-level level-${issue.level}`}>{issue.level === "error" ? "Error" : "Review"}</span>
              {issue.message}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

const REPORT_COPY: Record<ReportResult["status"], { title: string; detail: string }> = {
  generated: {
    title: "Preliminary report",
    detail: "",
  },
  blocked: {
    title: "Report not generated",
    detail:
      "Report generation was blocked because the structured record did not pass verification for automated reporting. " +
      "It was not sent to the language model.",
  },
  unavailable: {
    title: "Report service unavailable",
    detail: "The report generation service is not configured or not available, so no report was generated.",
  },
  failed: {
    title: "Report withheld",
    detail:
      "A report could not be completed or did not pass the output safety checks, so it has been withheld.",
  },
};

const CV_STILL_AVAILABLE = "The computer-vision findings above are unaffected and remain available for review.";

// `report.message` is intentionally not rendered: for unavailable and failed
// reports it can contain provider configuration or exception text.
function ReportSummary({ report }: { report: ReportResult }) {
  const copy = REPORT_COPY[report.status];
  const text = report.status === "generated" ? report.text?.trim() : undefined;

  return (
    <article className={`report-card report-${report.status}`} aria-labelledby="report-title">
      <div className="card-label">
        <span id="report-title">{copy.title}</span>
        <small className={`report-status status-${report.status}`}>{readable(report.status)}</small>
      </div>
      {text ? (
        <>
          <div className="report-body">
            <pre>{text}</pre>
          </div>
          <p className="report-provenance">
            Written by the language model from verified structured CV data only. The language model does not view the image.
          </p>
        </>
      ) : (
        <div className="unavailable-copy">
          <p>
            {report.status === "generated"
              ? "The report service returned an empty report, so there is no report text to show."
              : copy.detail}
          </p>
          <p>{CV_STILL_AVAILABLE}</p>
        </div>
      )}
    </article>
  );
}
